#!/usr/bin/env python3
"""Firmware signing for the STM32H523 FIDO2 bootloader (layout: drivers/boot.h).

  sign.py keygen KEY.pem                      new ECDSA P-256 signing key
  sign.py pubkey KEY.pem OUT.h                public key as C header for the bootloader
  sign.py sign KEY.pem APP.bin VERSION OUT    signed slot image OUT.bin and OUT.hex

The slot image is the 1 KB header followed by the app image, flashed at BOOT_SLOT_BASE
(SWD with OUT.hex, or USB DFU with OUT.bin).
"""
import hashlib
import os
import struct
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature

SLOT_BASE = 0x08008000
SLOT_SIZE = 0x00060000
HDR_SIZE = 0x400
HDR_MAGIC = 0x4B464942
HDR_VERSION = 1
HDR_SIGNED = 64


def load_key(path):
    with open(path, "rb") as f:
        key = serialization.load_pem_private_key(f.read(), password=None)
    if not isinstance(key, ec.EllipticCurvePrivateKey) or key.curve.name != "secp256r1":
        sys.exit(f"{path}: not an ECDSA P-256 private key")
    return key


def keygen(path):
    if os.path.exists(path):
        sys.exit(f"{path} exists, not overwriting")
    key = ec.generate_private_key(ec.SECP256R1())
    pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                            serialization.NoEncryption())
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(pem)
    print(f"new signing key {path}")


def pubkey(key_path, out_path):
    pub = load_key(key_path).public_key().public_numbers()
    xy = pub.x.to_bytes(32, "big") + pub.y.to_bytes(32, "big")
    body = ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in xy[i:i + 16]) for i in range(0, 64, 16))
    text = ("/* generated by tools/sign.py from the firmware signing key, do not edit */\n"
            "#pragma once\n#include <stdint.h>\n\n"
            "/* ECDSA P-256 public key, X || Y big endian */\n"
            f"static const uint8_t btl_pubkey[64] = {{\n{body}\n}};\n")
    # rewrite only on change, the bootloader would rebuild every time otherwise
    if not os.path.exists(out_path) or open(out_path).read() != text:
        with open(out_path, "w") as f:
            f.write(text)


def ihex(data, base):
    out = []

    def rec(kind, addr, payload):
        r = bytes([len(payload), addr >> 8, addr & 0xFF, kind]) + payload
        out.append(":" + (r + bytes([(-sum(r)) & 0xFF])).hex().upper())

    upper = None
    for off in range(0, len(data), 16):
        addr = base + off
        if addr >> 16 != upper:
            upper = addr >> 16
            rec(4, 0, struct.pack(">H", upper))
        rec(0, addr & 0xFFFF, data[off:off + 16])
    rec(1, 0, b"")
    return "\n".join(out) + "\n"


def sign(key_path, app_path, version, out):
    key = load_key(key_path)
    image = open(app_path, "rb").read()
    image += b"\xff" * (-len(image) % 16)
    if len(image) > SLOT_SIZE - HDR_SIZE:
        sys.exit(f"{app_path}: {len(image)} bytes does not fit the slot")

    signed = struct.pack("<4I", HDR_MAGIC, HDR_VERSION, version, len(image))
    signed += hashlib.sha256(image).digest() + b"\xff" * 16
    assert len(signed) == HDR_SIGNED
    r, s = decode_dss_signature(key.sign(signed, ec.ECDSA(hashes.SHA256())))
    hdr = signed + r.to_bytes(32, "big") + s.to_bytes(32, "big")
    slot = hdr + b"\xff" * (HDR_SIZE - len(hdr)) + image

    with open(out + ".bin", "wb") as f:
        f.write(slot)
    with open(out + ".hex", "w") as f:
        f.write(ihex(slot, SLOT_BASE))
    print(f"signed {os.path.basename(out)}.bin: version {version}, {len(image)} bytes")


def main():
    args = sys.argv[1:]
    if args[:1] == ["keygen"] and len(args) == 2:
        keygen(args[1])
    elif args[:1] == ["pubkey"] and len(args) == 3:
        pubkey(args[1], args[2])
    elif args[:1] == ["sign"] and len(args) == 5:
        sign(args[1], args[2], int(args[3], 0), args[4])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
